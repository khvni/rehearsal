// Records a full live run in the dashboard (light mode). Usage: node scripts/record-dashboard.mjs <outDir> [goal]
import { chromium } from "playwright";
import { cursorScript } from "./cursor.mjs";
const out = process.argv[2] ?? "/tmp/footage";
const goal = process.argv[3] ?? "Find the conference schedule";
const base = process.env.BASE_URL ?? "http://localhost:3000";
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 }, deviceScaleFactor: 1.5, recordVideo: { dir: out, size: { width: 1920, height: 1200 } }, colorScheme: "light" });
await ctx.addInitScript(cursorScript);
await ctx.addInitScript(() => { const s = document.createElement("style"); s.textContent = "nextjs-portal{display:none!important}"; document.addEventListener("DOMContentLoaded", () => document.head.appendChild(s)); });
const page = await ctx.newPage();
const t0 = Date.now();
const mark = (label) => console.log(`${((Date.now() - t0) / 1000).toFixed(1)}s ${label}`);
await page.goto(base, { waitUntil: "networkidle" });
await page.waitForTimeout(1200);
const goalBox = page.locator("textarea");
const box = await goalBox.boundingBox();
await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2, { steps: 25 });
await goalBox.click();
await page.keyboard.press("Control+A");
mark("typing");
await page.keyboard.type(goal, { delay: 55 });
await page.waitForTimeout(500);
const btn = page.getByRole("button", { name: "Start rehearsal" });
const bb = await btn.boundingBox();
await page.mouse.move(bb.x + bb.width / 2, bb.y + bb.height / 2, { steps: 20 });
await page.waitForTimeout(250);
await btn.click();
mark("start");
await page.waitForURL(/experiments\//);
await page.waitForTimeout(1500);
const run = page.getByRole("button", { name: "Run all steps" });
const rb = await run.boundingBox();
await page.mouse.move(rb.x + rb.width / 2, rb.y + rb.height / 2, { steps: 20 });
await page.waitForTimeout(300);
await run.click();
mark("run");
await page.mouse.move(800, 600, { steps: 20 });
await page.getByRole("button", { name: /Run again/ }).waitFor({ timeout: 600000 });
mark("done");
await page.waitForTimeout(2500);
// Tour the results slowly, scrolling the page (the graph pane would eat wheel events).
await page.mouse.move(1240, 400, { steps: 15 });
const scrollTo = async (sel, label) => {
  await page.evaluate((s) => { const el = document.querySelector(s) ?? [...document.querySelectorAll("h2,h3")].find((h) => h.textContent?.includes(s)); el?.scrollIntoView({ behavior: "smooth", block: "start" }); }, sel);
  mark(label);
  await page.waitForTimeout(3500);
};
await scrollTo("Browser runs", "runs");
await scrollTo("Findings", "findings");
await scrollTo("spec.md", "spec");
console.log("url", page.url());
await ctx.close();
await browser.close();
